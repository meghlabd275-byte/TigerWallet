#!/usr/bin/env python3
"""Regenerate master_wallet/backend/chain_registry_data.go from the canonical registry.

Run from the repository root:

    python3 tools/fetch_chain_registry.py        # downloads tools/cache/chains.json
    python3 tools/gen_mw_chain_registry.py       # rewrites the MasterWallet registry

Why this script exists
----------------------
MasterWallet keeps its own EVM chain list because it seeds a different table
(user_chains_evm, keyed by chain_id) from a different service. That list was
originally generated by walking the upstream registry in ascending chain-id
order and stopping at 120 entries, which silently dropped every chain whose id
sorts above the cut: Base (8453), Arbitrum One (42161), OP Mainnet (10), Celo
(42220), Linea (59144), Scroll (534352), Mantle (5000), zkSync Era (324) and
Blast (81457) were all absent while chain ids in the tens of thousands were
present. A user could not add those networks.

Rather than patch the list, this script derives it from
go/wallet_api/chains_evm_data.go, which is itself generated from the canonical
ethereum-lists registry by tools/gen_evm_chains.py. One source of truth, two
emitters, so the two services can no longer disagree about which chains exist.

The non-EVM list is not touched: it is curated by hand (chain types, bech32
prefixes, SLIP-44 coin types) and has no upstream equivalent.
"""
import re
import sys

CANONICAL = "go/wallet_api/chains_evm_data.go"
TARGET = "master_wallet/backend/chain_registry_data.go"

# MasterWallet seeds user_chains_evm with a NUMERIC chain_id, while the wallet
# API models EVM chains with the EIP-155 id too, so the two agree field for
# field. This header is rewritten so a regenerated file explains itself.
EVM_HEADER = """// defaultEVMChains returns the canonical EVM mainnet chains, derived from
// go/wallet_api/chains_evm_data.go so both services agree on which chains
// exist. Regenerate with tools/gen_mw_chain_registry.py; do not edit by hand.
var defaultEVMChains = []defaultChain{"""


def parse_canonical(path):
    """Returns a list of dicts describing each chain in the canonical file."""
    text = open(path, encoding="utf-8").read()
    chains = []
    for match in re.finditer(r"\{\s*\n(.*?)\n\s*\},", text, re.S):
        body = match.group(1)
        fields = {}
        for key in ("ID", "Decimals", "CoinType"):
            found = re.search(rf"\b{key}:\s*(\d+)", body)
            if found:
                fields[key] = int(found.group(1))
        for key in ("Name", "Symbol", "RPCEndpoint", "DerivationPath", "ExplorerURL", "ChainType"):
            found = re.search(rf'\b{key}:\s*"([^"]*)"', body)
            if found:
                fields[key] = found.group(1)
        if "ID" not in fields or "Name" not in fields:
            continue
        # Testnets are excluded from the shipped registry for the same reason
        # the canonical generator excludes them: worthless balances and a
        # non-production RPC would misrepresent the network as usable.
        if fields.get("IsTestnet") == "true" or re.search(
            r"testnet|sepolia|goerli|holesky|devnet", fields["Name"], re.I
        ):
            continue
        chains.append(fields)
    return chains


def go_string(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


DEFAULT_PATH = "m/44'/60'/0'/0/0"


def render(chain):
    parts = [
        f"ChainID: {chain['ID']}",
        f"Name: {go_string(chain['Name'])}",
        f"Symbol: {go_string(chain.get('Symbol', 'ETH'))}",
        f"RPCURL: {go_string(chain.get('RPCEndpoint', ''))}",
        f"ExplorerURL: {go_string(chain.get('ExplorerURL', ''))}",
        f"Decimals: {chain.get('Decimals', 18)}",
        f"DerivationPath: {go_string(chain.get('DerivationPath', DEFAULT_PATH))}",
    ]
    return "{" + ", ".join(parts) + "},"


def main():
    chains = parse_canonical(CANONICAL)
    if not chains:
        print(f"error: no chains parsed from {CANONICAL}", file=sys.stderr)
        return 1

    # A chain with no RPC cannot be used, and shipping one with an empty
    # endpoint would present it as working.
    usable = [c for c in chains if c.get("RPCEndpoint")]
    dropped = [c for c in chains if not c.get("RPCEndpoint")]
    for chain in dropped:
        print(f"  skipped {chain['Name']} (chain_id={chain['ID']}): no RPC endpoint")

    # The canonical file can carry the same id twice when a chain appears under
    # several registry names; the first wins so the output stays stable.
    seen = set()
    unique = []
    for chain in usable:
        if chain["ID"] in seen:
            continue
        seen.add(chain["ID"])
        unique.append(chain)
    unique.sort(key=lambda c: c["ID"])

    text = open(TARGET, encoding="utf-8").read()
    marker = "var defaultEVMChains = []defaultChain{"
    if marker not in text:
        print(f"error: {TARGET} has no defaultEVMChains block", file=sys.stderr)
        return 1

    # Replace only the EVM slice; the non-EVM slice that follows is preserved.
    start = text.index(marker)
    end = text.index("// defaultNonEVMChains", start)
    body = "\n".join("\t" + render(c) for c in unique)
    replaced = text[:start] + EVM_HEADER + "\n" + body + "\n}\n\n" + text[end:]

    open(TARGET, "w", encoding="utf-8").write(replaced)

    print(f"canonical chains: {len(chains)}")
    print(f"emitted: {len(unique)} EVM chains")
    return 0


if __name__ == "__main__":
    sys.exit(main())
