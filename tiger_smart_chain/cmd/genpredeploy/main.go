// Command genpredeploy renders chain/predeploy_data.go from the compiled
// contract artifacts in contracts/artifacts.
//
// The genesis predeploys (RUSD, WTGR) are part of the consensus surface: their
// runtime bytecode and initial storage are committed into the genesis block, so
// the values must be reproducible and reviewable. Rather than paste a multi
// kilobyte hex blob into a source file by hand, this generator reads the
// compiler output and emits the Go source. Run it through `make predeploy`
// whenever a contract under contracts/ changes.
package main

import (
	"encoding/hex"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// predeployArtifact describes one genesis predeploy contract.
type predeployArtifact struct {
	// Name is the Go identifier suffix, e.g. "RUSD".
	Name string
	// Source is the contract source file, relative to the module root.
	Source string
}

var artifacts = []predeployArtifact{
	{Name: "RUSD", Source: "contracts/RUSD.sol"},
	{Name: "WTGR", Source: "contracts/WTGR.sol"},
}

// storageLayout mirrors the subset of solc's --storage-layout output this
// generator needs to sanity check that the declared layout has not moved.
type storageLayout struct {
	Storage []struct {
		Slot  string `json:"slot"`
		Label string `json:"label"`
	} `json:"storage"`
}

func main() {
	root := "."
	if len(os.Args) > 1 {
		root = os.Args[1]
	}
	artifactsDir := filepath.Join(root, "contracts", "artifacts")

	var b strings.Builder
	b.WriteString("package chain\n\n")
	b.WriteString("// Code generated by cmd/genpredeploy from contracts/*.sol. DO NOT EDIT.\n")
	b.WriteString("//\n")
	b.WriteString("// Regenerate with `make predeploy` after changing any contract under\n")
	b.WriteString("// contracts/. The bytecode below is the solc --optimize --optimize-runs 200\n")
	b.WriteString("// --evm-version london runtime image of the corresponding source file, and\n")
	b.WriteString("// it is committed into the genesis state by BuildGenesis.\n\n")

	for _, a := range artifacts {
		bytecodePath := filepath.Join(artifactsDir, a.Name+".bin-runtime")
		raw, err := os.ReadFile(bytecodePath)
		if err != nil {
			fatalf("read %s: %v", bytecodePath, err)
		}
		hexStr := strings.TrimSpace(string(raw))
		hexStr = strings.TrimPrefix(hexStr, "0x")
		if hexStr == "" {
			fatalf("%s is empty", bytecodePath)
		}
		if _, err := hex.DecodeString(hexStr); err != nil {
			fatalf("%s is not valid hex: %v", bytecodePath, err)
		}

		layoutPath := filepath.Join(artifactsDir, a.Name+"_storage.json")
		if _, err := os.Stat(layoutPath); err != nil {
			fatalf("missing storage layout %s: %v", layoutPath, err)
		}
		var layout storageLayout
		layoutRaw, err := os.ReadFile(layoutPath)
		if err != nil {
			fatalf("read %s: %v", layoutPath, err)
		}
		if err := json.Unmarshal(layoutRaw, &layout); err != nil {
			fatalf("parse %s: %v", layoutPath, err)
		}
		if len(layout.Storage) == 0 {
			fatalf("%s declares no storage slots", layoutPath)
		}
		var labels []string
		for i, s := range layout.Storage {
			if s.Slot != fmt.Sprint(i) {
				fatalf("%s: slot %d is %q, storage slots must be contiguous from 0", layoutPath, i, s.Slot)
			}
			labels = append(labels, s.Label)
		}

		fmt.Fprintf(&b, "// %sRuntime is the deployed runtime bytecode of %s (%s).\n",
			a.Name, a.Name, a.Source)
		fmt.Fprintf(&b, "//\n// Storage slots, in order: %s\n", strings.Join(labels, ", "))
		fmt.Fprintf(&b, "const %sRuntime = \"%s\"\n\n", a.Name, hexStr)
	}

	out := filepath.Join(root, "chain", "predeploy_data.go")
	if err := os.WriteFile(out, []byte(b.String()), 0o644); err != nil {
		fatalf("write %s: %v", out, err)
	}
	fmt.Printf("wrote %s (%d bytes)\n", out, b.Len())
}

func fatalf(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "genpredeploy: "+format+"\n", args...)
	os.Exit(1)
}
